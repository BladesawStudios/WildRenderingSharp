using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using Silk.NET.OpenGL;

// usage: gen <src root> <out dir>   — reads every .cs outside the Gpu project, writes GpuApi.cs and GpuEnums.cs.
string root = args[0], outDir = args[1];
var files = Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories)
    .Where(f => !f.Replace('\\', '/').Contains("/obj/") && !f.Contains("Generated") && !f.EndsWith("GpuApi.cs") && !f.Replace((char)92,(char)47).Contains("/vendor/") && !f.Replace((char)92,(char)47).Contains("/bin/")).ToList();
string all = string.Join("\n", files.Select(File.ReadAllText));
var methodsUsed = Regex.Matches(all, @"\b[A-Za-z_]*[gG][lL]\.([A-Z][A-Za-z0-9]*)").Select(m => m.Groups[1].Value).ToHashSet();
var asm = typeof(GL).Assembly;
var enums = asm.GetTypes().Where(t => t.IsEnum && t.Namespace == "Silk.NET.OpenGL" && t.IsPublic).ToDictionary(t => t.Name);
var enumUsed = enums.Keys.Where(n => Regex.IsMatch(all, @"\b" + n + @"\b")).ToHashSet();

string Type(Type t, out bool ok)
{
    ok = true;
    if (t == typeof(void)) return "void";
    if (t.IsByRef) { string inner = Type(t.GetElementType()!, out ok); if (t.GetElementType()!.IsEnum) ok = false; return inner; }
    if (t.IsPointer) return Type(t.GetElementType()!, out ok) + "*";
    if (t.IsArray) return Type(t.GetElementType()!, out ok) + "[]";
    if (t.IsGenericParameter) return t.Name;
    if (t.IsEnum && t.Namespace == "Silk.NET.OpenGL") { if (!enumUsed.Contains(t.Name)) ok = false; return t.Name; }
    if (t.IsGenericType)
    {
        string n = t.Name[..t.Name.IndexOf('`')];
        var parts = new List<string>(); bool all2 = true;
        foreach (var a in t.GetGenericArguments()) { parts.Add(Type(a, out bool o)); all2 &= o; }
        ok = all2;
        return $"{t.Namespace}.{n}<{string.Join(", ", parts)}>";
    }
    if (t.Namespace == "Silk.NET.OpenGL") { ok = false; return t.Name; }
    return t switch
    {
        _ when t == typeof(int) => "int", _ when t == typeof(uint) => "uint", _ when t == typeof(float) => "float", _ when t == typeof(double) => "double",
        _ when t == typeof(bool) => "bool", _ when t == typeof(byte) => "byte", _ when t == typeof(sbyte) => "sbyte", _ when t == typeof(short) => "short", _ when t == typeof(ushort) => "ushort",
        _ when t == typeof(long) => "long", _ when t == typeof(ulong) => "ulong", _ when t == typeof(nint) => "nint", _ when t == typeof(nuint) => "nuint", _ when t == typeof(string) => "string",
        _ => (t.FullName ?? t.Name),
    };
}

bool ConvIn(Type t) => t.IsEnum && t.Namespace == "Silk.NET.OpenGL";
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>The GL calls the renderer makes, under the renderer's own names. Regenerated from the code that uses them.</auto-generated>");
sb.AppendLine("#pragma warning disable CS1591, CS8981");
sb.AppendLine("using System.Numerics;\nnamespace KingRenderingSharp.Gpu;\n");
sb.AppendLine("/// <summary>The GL calls the renderer makes; the only type that holds the driver's API.</summary>\npublic sealed unsafe partial class GpuApi\n{");
int count = 0; var emitted = new HashSet<string>();
var overloads = asm.GetType("Silk.NET.OpenGL.GLOverloads")!.GetMethods(BindingFlags.Public | BindingFlags.Static).Where(x => x.GetParameters().Length > 0 && x.GetParameters()[0].ParameterType == typeof(GL));
foreach (var m in typeof(GL).GetMethods(BindingFlags.Public | BindingFlags.Instance).Where(x => x.DeclaringType == typeof(GL)).Concat(overloads).OrderBy(m => m.Name).ThenBy(m => m.GetParameters().Length))
{
    if (!methodsUsed.Contains(m.Name) || m.GetCustomAttribute<ObsoleteAttribute>() != null ) continue;
    bool ext = m.IsStatic; var ps = m.GetParameters().Skip(ext ? 1 : 0).ToArray();
    bool ok = true; var decl = new List<string>(); var call = new List<string>();
    foreach (var p in ps)
    {
        string ty = Type(p.ParameterType, out bool o); ok &= o;
        string mod = p.ParameterType.IsByRef ? (p.IsOut ? "out " : p.IsIn ? "in " : "ref ") : "";
        decl.Add($"{mod}{ty} @{p.Name}");
        string arg = ConvIn(p.ParameterType) ? $"(Silk.NET.OpenGL.{p.ParameterType.Name})@{p.Name}" : "@" + p.Name!;
        call.Add($"{mod}{arg}");
    }
    string ret = Type(m.ReturnType, out bool ro); ok &= ro || m.ReturnType.IsEnum && enumUsed.Contains(m.ReturnType.Name);
    if (!ok || m.Name == "IsExtensionPresent" || m.Name == "TryGetExtension" || decl.Any(d => d.Contains("Silk.NET.Maths") || d.Contains("Span<string>") || ((d.Contains('<') || d.Contains('*') || d.Contains("[]")) && Regex.Split(d, @"\W+").Any(enumUsed.Contains)))) continue;
    string gen = "", where = "";
    if (m.IsGenericMethod)
    {
        var ga = m.GetGenericArguments();
        gen = "<" + string.Join(", ", ga.Select(a => a.Name)) + ">";
        where = string.Join(" ", ga.Select(a => a.GenericParameterAttributes.HasFlag(GenericParameterAttributes.NotNullableValueTypeConstraint) ? $"where {a.Name} : unmanaged" : ""));
    }
    string body = ext ? $"Silk.NET.OpenGL.GLOverloads.{m.Name}{gen}(Native, {string.Join(", ", call)})" : $"Native.{m.Name}{gen}({string.Join(", ", call)})";
    if (m.ReturnType.IsEnum && ConvIn(m.ReturnType)) body = $"({ret}){body}";
    string sig = $"    internal {ret} {m.Name}{gen}({string.Join(", ", decl)}) {where}".TrimEnd();
    string key = sig;
    if (!emitted.Add(key)) continue;
    sb.AppendLine(sig + (ret == "void" ? $" => {body};" : $" => {body};"));
    count++;
}
sb.AppendLine("}");
File.WriteAllText(Path.Combine(outDir, "GpuApi.Generated.cs"), sb.ToString());

// enums: only the members the code names
var eb = new StringBuilder();
eb.AppendLine("// <auto-generated>The values the renderer passes to GL, under the renderer's own names.</auto-generated>\n#pragma warning disable CS1591\nnamespace KingRenderingSharp.Gpu;\n");
foreach (var name in enumUsed.Order())
{
    var t = enums[name];
    var used = Enum.GetNames(t).Where(n => Regex.IsMatch(all, @"\b" + name + @"\." + n + @"\b")).ToList();
    var flags = t.GetCustomAttribute<FlagsAttribute>() != null;
    var seen = new Dictionary<object, string>();
    var under = Enum.GetUnderlyingType(t);
    string u = under == typeof(uint) ? "uint" : under == typeof(int) ? "int" : under.Name.ToLowerInvariant();
    eb.AppendLine((flags ? "[System.Flags]\n" : "") + $"internal enum {name} : {u}\n{{");
    foreach (var n in used)
        eb.AppendLine($"    {n} = {Convert.ChangeType(Enum.Parse(t, n), under)},");
    eb.AppendLine("}\n");
}
File.WriteAllText(Path.Combine(outDir, "GpuEnums.Generated.cs"), eb.ToString());
Console.WriteLine($"methods {count}, enums {enumUsed.Count}, used names {methodsUsed.Count}");
